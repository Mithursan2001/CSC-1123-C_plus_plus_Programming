#include<iostream>
using namespace std;
int main(){

    int num1,num2;
    cout<<"Enter the number 1 :\n";
    cin>>num1;
    cout<<"Enter the number 2 :\n";
    cin>>num2;
    cout<<num1<<" + "<<num2<<" = "<<(num1 + num2)<<"\n";
    cout<<num1<<" - "<<num2<<" = "<<(num1 - num2)<<"\n";
    cout<<num1<<" * "<<num2<<" = "<<(num1 * num2)<<"\n";
    cout<<num1<<" / "<<num2<<" = "<<(num1 / num2)<<"\n";
    cout<<num1<<" % "<<num2<<" = "<<(num1 % num2)<<"\n"; //remainder


return 0;
}
